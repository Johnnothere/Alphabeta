const LABEL: Record<Social["kind"], string> = {
  github: "GitHub",
  x: "X",
  linkedin: "LinkedIn",
  instagram: "Instagram",
  discord: "Discord",
  youtube: "YouTube",
  web: "Website",
  email: "Email",
};

export function socialLabel(kind: Social["kind"]) {
  return LABEL[kind];
}

export function socialHref(s: Social) {
  return s.kind === "email" && !s.href.startsWith("mailto:") ? `mailto:${s.href}` : s.href;
}
